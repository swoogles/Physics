#!/usr/bin/env python3
"""Sample scenario parameters, run previews, score them, keep the good ones.

The point of this script is to turn "go make some cool shit" into something
repeatable: it samples the handful of knobs that actually change how a run
looks, runs each one as a short low-resolution preview, ranks the results from
the run reports the simulator writes, and can then re-render the winners at
full resolution from the exact same seed.

    tools/run_batch.py sample --archetype pair --runs 12
    tools/run_batch.py report batches/<batch> --contact-sheet --reel
    tools/run_batch.py render batches/<batch> --exclude pair-04 --top 3 --res 1440p

Every run leaves behind <name>.mp4 and <name>.json in the batch directory. The
json is enough to reproduce the run exactly.
"""

import argparse
import json
import math
import os
import random
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BINARY = REPO / "build" / "PhysicsSandbox"

# --------------------------------------------------------------------------
# Parameter sampling
#
# These ranges are where the interesting behaviour lives. Everything is
# dimensionless, so the same range works whatever scale the scenario runs at.
# --------------------------------------------------------------------------


def log_uniform(rng, low, high):
    return math.exp(rng.uniform(math.log(low), math.log(high)))


def sample_cluster(rng):
    magnitude = rng.choice([0.0, 0.15, 0.3, 0.45, 0.6, 0.75, 1.0])

    # The camera looks down z, so a z-spin flattens the cloud face-on and reads
    # as a circle. An in-plane axis shows the flattening. Sample both, favouring
    # the one you can actually see.
    if rng.random() < 0.7:
        spin = "%s,0,0" % magnitude
    else:
        spin = "0,0,%s" % magnitude

    return {
        "scenario.type": "cluster",
        # Below ~0.2 collapses hard; near 0.5 barely evolves.
        "scenario.virial_ratio": round(log_uniform(rng, 0.06, 0.55), 3),
        "cluster.radius": "2.0e7",
        "cluster.spin": spin,
        "cluster.dispersion": round(rng.uniform(0.05, 0.4), 2),
    }


def sample_pair(rng):
    return {
        "scenario.type": "pair",
        "scenario.virial_ratio": -1,
        "pair.separation": "%.2e" % (rng.uniform(3.0, 7.0) * 1e7),
        # 0 is a head-on smash; 0.4-0.9 is where tidal tails come from.
        "pair.impact_parameter": round(rng.uniform(0.0, 1.2), 2),
        # 1.0 is parabolic. Above that the pair may not stay bound.
        "pair.approach_speed": round(rng.uniform(0.3, 1.15), 2),
        "pair.mass_ratio": round(log_uniform(rng, 1.0, 10.0), 2),
        "pair.spin_a": round(rng.uniform(-0.6, 0.6), 2),
        "pair.spin_b": round(rng.uniform(-0.6, 0.6), 2),
        "pair.dispersion": round(rng.uniform(0.05, 0.25), 2),
    }


def sample_chaotic(rng):
    # The band each group's own temperature is drawn from. The bottom stays
    # cold enough that something always collapses promptly; the top is sampled
    # wide because that is the knob that decides whether a run is eight clumps
    # all doing the same thing, or clumps arriving into clouds that were
    # holding themselves up until then.
    coldest = log_uniform(rng, 0.01, 0.10)
    warmest = min(0.9, coldest * log_uniform(rng, 2.0, 30.0))

    return {
        "scenario.type": "chaotic",
        "scenario.virial_ratio": round(log_uniform(rng, 0.08, 0.5), 3),
        "chaotic.groups": rng.randint(3, 9),
        "chaotic.spread": "3.0e7",
        "chaotic.size_fraction": round(rng.uniform(0.1, 0.28), 3),
        "chaotic.infall": round(rng.uniform(0.2, 0.8), 2),
        "chaotic.tangential": round(rng.uniform(0.0, 0.6), 2),
        "chaotic.spin_max": round(rng.uniform(0.0, 0.6), 2),
        "chaotic.mass_spread": round(rng.uniform(1.0, 4.0), 2),
        "chaotic.thickness": round(rng.uniform(0.05, 0.5), 2),
        "chaotic.dispersion": round(rng.uniform(0.05, 0.25), 2),
        "chaotic.group_virial_min": round(coldest, 3),
        "chaotic.group_virial_max": round(warmest, 3),
    }


def sample_diamond(rng):
    return {
        "scenario.type": "diamond",
        "scenario.virial_ratio": round(log_uniform(rng, 0.08, 0.5), 3),
        "diamond.groups": rng.randint(3, 10),
        "diamond.ring_radius": "%.2e" % (rng.uniform(1.5, 4.0) * 1e7),
        "diamond.infall": round(rng.uniform(0.2, 0.8), 2),
        "diamond.swirl": round(rng.uniform(0.0, 0.6), 2),
        "diamond.spin": round(rng.uniform(0.0, 0.5), 2),
        "diamond.dispersion": round(rng.uniform(0.05, 0.25), 2),
    }


SAMPLERS = {
    "cluster": sample_cluster,
    "pair": sample_pair,
    "chaotic": sample_chaotic,
    "diamond": sample_diamond,
}


BASE_CONFIG = """# Generated by tools/run_batch.py - edit the batch script, not this file.
forceCalculationMethod=octree
parallel=true
octree_theta=0.5
maximum_runtime=150

numShapes={particles}
mass=598910
sandbox_width=5.2e6

dt=auto
frames_per_crossing={frames_per_crossing}

collision_radius_multiplier=30.0
merge_target_fraction=0.9
merge_target_seconds=120
minimum_merges_per_frame={min_merges}

velocity_damping=0.9995
boundary_strength=0.001
boundary_radius_factor=1.5
"""


def write_config(path, params, particles, frames_per_crossing, min_merges, name):
    lines = [BASE_CONFIG.format(
        particles=particles,
        frames_per_crossing=frames_per_crossing,
        min_merges=min_merges,
    )]
    lines.append("\nscenario.name=%s\n" % name)
    for key, value in params.items():
        lines.append("%s=%s\n" % (key, value))
    path.write_text("".join(lines))


# --------------------------------------------------------------------------
# Running
# --------------------------------------------------------------------------


def run_one(config, output, seed, res, max_frames, quiet=True):
    """Runs one simulation. Output goes to <video>.log so a failed encode can be
    read back - discarding it once hid an ffmpeg error for a whole batch."""
    command = [
        str(BINARY),
        "--config", str(config),
        "--out", str(output),
        "--seed", str(seed),
        "--record",
        "--res", res,
        "--max-frames", str(max_frames),
    ]

    log_path = Path(output).with_suffix(".log")
    with open(log_path, "wb") as log:
        result = subprocess.run(
            command,
            cwd=str(REPO),
            stdout=log if quiet else None,
            stderr=subprocess.STDOUT if quiet else None,
        )
    return result.returncode


def verify_video(path):
    """(ok, description). A run that simulated for an hour and wrote nothing is
    the expensive failure, so check the file is real before moving on."""
    video = Path(path)
    if not video.exists():
        return False, "no file was written"

    size = video.stat().st_size
    if size == 0:
        return False, "file is empty (0 bytes) - the encode failed"
    if size < 20_000:
        return False, "file is only %d bytes" % size

    try:
        probe = subprocess.run(
            ["ffprobe", "-v", "error", "-show_entries", "format=duration",
             "-of", "csv=p=0", str(video)],
            capture_output=True, text=True)
        duration = float(probe.stdout.strip())
    except (ValueError, OSError):
        return False, "ffprobe could not read it"

    if duration <= 0:
        return False, "zero duration"

    return True, "%.0fs, %.0f MB" % (duration, size / 1e6)


def report_failure(name, video, note):
    print("\n  !! %s produced no usable video: %s" % (name, note))
    log_path = Path(video).with_suffix(".log")
    if log_path.exists():
        tail = log_path.read_text(errors="replace").splitlines()[-12:]
        print("  --- last lines of %s ---" % log_path.name)
        for line in tail:
            print("  | %s" % line)
    print("")


# --------------------------------------------------------------------------
# Scoring
#
# Reads the sidecar the simulator wrote and asks four questions:
#   did it collapse, did it stay in frame, did anything build up, did it move?
# --------------------------------------------------------------------------


def clamp(value, low=0.0, high=1.0):
    return max(low, min(high, value))


def score_run(report):
    history = report.get("history") or []
    if len(history) < 3:
        return 0.0, {"reason": "too short"}

    radii = [sample["rms_radius_m"] for sample in history if sample["rms_radius_m"] > 0]
    if not radii:
        return 0.0, {"reason": "no radius history"}

    initial = radii[0]
    smallest = min(radii)
    final = radii[-1]
    largest_fraction = history[-1]["largest_mass_fraction"]

    # Did it actually fall together at some point?
    collapse = clamp(1.0 - smallest / initial)

    # Did it stay watchable, or did it spray off screen?
    expansion = final / initial
    bounded = 1.0 if expansion <= 1.5 else clamp(1.0 - (expansion - 1.5) / 2.0)

    # Did a dominant body build up? 5% of total mass in one object is plenty.
    structure = clamp(largest_fraction / 0.05)

    # Did anything happen at all, or was it a static blob?
    liveliness = clamp((max(radii) - smallest) / initial)

    score = (0.30 * collapse
             + 0.20 * bounded
             + 0.25 * structure
             + 0.15 * liveliness
             + 0.10 * (1.0 if report.get("completed") else 0.0))

    return score, {
        "collapse": round(collapse, 3),
        "bounded": round(bounded, 3),
        "structure": round(structure, 3),
        "liveliness": round(liveliness, 3),
        "expansion": round(expansion, 3),
        "largest_mass_fraction": largest_fraction,
    }


def load_reports(batch_dir):
    reports = []
    for sidecar in sorted(Path(batch_dir).glob("*.json")):
        if sidecar.name == "index.json":
            continue
        try:
            report = json.loads(sidecar.read_text())
        except json.JSONDecodeError:
            print("  ! unreadable report: %s" % sidecar.name)
            continue

        video = Path(report.get("video_path", ""))
        if not video.is_absolute():
            video = REPO / video
        size = video.stat().st_size if video.exists() else 0

        score, parts = score_run(report)
        # Catches the 0-byte and few-hundred-byte files a crashed run leaves.
        if size < 20_000:
            score, parts = 0.0, {"reason": "empty or missing video (%d bytes)" % size}

        reports.append({
            "name": sidecar.stem,
            "sidecar": str(sidecar),
            "video": str(video),
            "video_bytes": size,
            "seed": report.get("seed"),
            "scenario": report.get("scenario", {}),
            "score": round(score, 4),
            "parts": parts,
        })

    reports.sort(key=lambda entry: entry["score"], reverse=True)
    return reports


